// HidDescriptor.kt: the single combined HID report descriptor (see "HID report contract" in architecture.md).
package dev.padlink.hid

/** Report IDs and the combined descriptor registered by both Bluetooth stacks. */
object HidDescriptor {
    const val ID_KEYBOARD = 1
    const val ID_MOUSE = 2
    const val ID_CONSUMER = 3
    const val ID_PEN = 4

    /** HID subclass advertised in SDP: combo keyboard and pointing device. */
    val SUBCLASS_COMBO: Byte = 0xC0.toByte()

    /** Keyboard collection from the original app, with the key-array logical maximum fixed to 255. */
    private val KEYBOARD = bytes(
        0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, ID_KEYBOARD,
        0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
        0x75, 0x08, 0x95, 0x01, 0x81, 0x01,
        0x75, 0x08, 0x95, 0x05, 0x15, 0x00, 0x26, 0xFF, 0x00,
        0x05, 0x07, 0x19, 0x00, 0x29, 0xFF, 0x81, 0x00,
        0xC0,
    )

    /** Mouse collection identical to the original app: 5 buttons, 8-bit X/Y/wheel, 8-bit AC Pan. */
    private val MOUSE = bytes(
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, ID_MOUSE,
        0x09, 0x01, 0xA1, 0x00,
        0x05, 0x09, 0x19, 0x01, 0x29, 0x05, 0x15, 0x00, 0x25, 0x01,
        0x75, 0x01, 0x95, 0x05, 0x81, 0x02,
        0x75, 0x03, 0x95, 0x01, 0x81, 0x01,
        0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F,
        0x75, 0x08, 0x95, 0x03, 0x81, 0x06,
        0x05, 0x0C, 0x0A, 0x38, 0x02, 0x95, 0x01, 0x81, 0x06,
        0xC0, 0xC0,
    )

    /** Consumer-control collection identical to the original app. */
    private val CONSUMER = bytes(
        0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01, 0x85, ID_CONSUMER,
        0x19, 0x00, 0x2A, 0xFF, 0x03, 0x75, 0x0C, 0x95, 0x01, 0x15, 0x00, 0x26, 0xFF, 0x03, 0x81, 0x00,
        0x75, 0x04, 0x95, 0x01, 0x81, 0x01,
        0xC0,
    )

    /** Pen digitizer: tip, barrel, eraser, invert, in range, absolute X/Y, pressure, tilt. */
    private val PEN = bytes(
        0x05, 0x0D, 0x09, 0x02, 0xA1, 0x01, 0x85, ID_PEN,
        0x09, 0x20, 0xA1, 0x00,
        0x09, 0x42, 0x09, 0x44, 0x09, 0x45, 0x09, 0x3C, 0x09, 0x32,
        0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x05, 0x81, 0x02,
        0x95, 0x03, 0x81, 0x03,
        // X: 0..32767 over 16.00 inches, Y: 0..32767 over 9.00 inches (16:9 reference tablet).
        0x05, 0x01, 0x55, 0x0E, 0x65, 0x13, 0x75, 0x10, 0x95, 0x01,
        0x15, 0x00, 0x26, 0xFF, 0x7F, 0x35, 0x00,
        0x09, 0x30, 0x46, 0x40, 0x06, 0x81, 0x02,
        0x09, 0x31, 0x46, 0x84, 0x03, 0x81, 0x02,
        0x55, 0x00, 0x65, 0x00, 0x45, 0x00,
        0x05, 0x0D, 0x09, 0x30, 0x15, 0x00, 0x26, 0xFF, 0x0F, 0x75, 0x10, 0x95, 0x01, 0x81, 0x02,
        0x09, 0x3D, 0x09, 0x3E, 0x15, 0xC4, 0x25, 0x3C, 0x65, 0x14, 0x75, 0x08, 0x95, 0x02, 0x81, 0x02,
        0x65, 0x00,
        0xC0, 0xC0,
    )

    /** Complete descriptor: keyboard, mouse, consumer, pen. */
    val DESCRIPTOR: ByteArray = KEYBOARD + MOUSE + CONSUMER + PEN

    /** Converts unsigned byte literals into a byte array. */
    private fun bytes(vararg values: Int): ByteArray = ByteArray(values.size) { values[it].toByte() }
}
